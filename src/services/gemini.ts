/**
 * Calls Google Gemini REST API using the v1beta endpoint.
 */
async function callGemini(apiKey: string, prompt: string, systemInstruction?: string): Promise<string> {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`;

  const requestBody: any = {
    contents: [
      {
        parts: [{ text: prompt }]
      }
    ]
  };

  if (systemInstruction) {
    requestBody.systemInstruction = {
      parts: [{ text: systemInstruction }]
    };
  }

  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify(requestBody)
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    throw new Error(errorData.error?.message || `Gemini API responded with status ${response.status}`);
  }

  const data = await response.json();
  const candidate = data.candidates?.[0];
  const text = candidate?.content?.parts?.[0]?.text;
  if (!text) {
    throw new Error("No response generated by Gemini model.");
  }
  return text;
}

/**
 * Validates Gemini API Key by sending a ping prompt
 */
export async function testGeminiApiKey(apiKey: string): Promise<boolean> {
  if (!apiKey || apiKey.trim().length === 0) {
    return false;
  }
  try {
    const testRes = await callGemini(apiKey, "Respond only with the single word 'OK'.");
    return testRes.toLowerCase().includes("ok");
  } catch (err) {
    console.error("Gemini key validation error:", err);
    return false;
  }
}

